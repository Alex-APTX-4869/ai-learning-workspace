"""正常访谈与自动补问共用的决策规则，不另加一次模型审查调用。"""

QUESTION_POLICY = """
问题与选项的共同设计规则（正常提问和补问同样适用）：
- 先区分：已确认的必学内容、为目标推导但尚未确认的前置条件、当前真正未知的一个决策。保留初始需求和全部历史回答中的承诺；新回答只调整本题维度，不抹掉此前范围。
- baseline 用一条简短中文说明与本题有关、已经明确的共同前提。没有可靠依据则填空字符串，不把模型假设或教材覆盖写成用户确认。它是提问上下文，不是用户的新承诺。
- 每题只比较一个维度。不要把学习主题、深度、练习形式、考试题型、是否编程混在同一组选项中。
- 范围/深度题：共同必学内容所有方案都保留，只选择在它之上扩展到哪里。适合递进时写清“保留前项，再增加什么”，不要把基础、练习、高阶知识列成相互排斥的单选主题。选较深方案不等于跳过基础。
- 偏好题：比较同一维度的取舍，例如相同范围下先看例子还是先看原理；偏好不等于排除非首选内容。不是所有题都必须从少到多，也不默认越多越好。
- 可以同时需要的独立主题不能被强行做成单选。先确定共同范围，再只问一个尚未明确的主题是否纳入；不要罗列所有主题组合，也不要用含糊的“混合/都要”掩盖维度混杂。
- 事实题：问用户实际知道什么，不问“你猜考试考什么”。考试/作业要求以明确说明为依据，不能从讲义有公式推断“不考代码”。证据不足时提供明确的“不确定/尚未收到说明”选项，保留未知，并说明暂按什么可调整方案准备。
- 若只是要确定是否需要代码，就直接问是否有明确编程要求，不同时问概念/计算偏好。已有代码经验也不等于考试必须写代码。
- 选项数量由本题的真实决策空间决定，不预设固定数量，不固定为三档或四档；足够覆盖主要情况即可，不凑数、不造近义项、不展开无意义组合。至少两个有区别的选择；“不确定”是事实状态，和前端的自由输入不是一回事。前端另有自由输入，不重复生成“其他”。
- 每项标题简短，description 讲清选择后的实际差别；每题恰好推荐一个，推荐不能伪装成对未知事实的断言。事实缺乏证据时推荐如实选“不确定”，不是推荐猜一个答案。
- 发出前自行检查：所有选择是否保留已确认范围？是否只在一个维度上不同？能同时成立的内容是否被错误排斥？用户是否有足够信息作答？数量是否恰好够用？不合格就在本次生成中改写，不输出检查过程。
- 问题、baseline、purpose、推荐依据分别简洁，不重复长篇推理；语言匹配用户基础，必要术语当场用普通话解释。
"""

SCOPE_PRESERVATION = """
范围继承：
- 通读初始需求和所有历史回答，不以最后一次选项替换整份需求。选项是本题维度的调整，未选择的选项不自动等于 scope_out。
- 学得更深仍保留已确认的基础；“重点/为主/偏好”不等于“只学/禁止其他内容”。只有明确排除才记为不学。
- baseline 是系统对已有信息的摘要，不是新增用户授权。若自由回答明确纠正此前前提，以用户的明确纠正为准；不明确的冲突保留待确认。
- 用户选择“不确定”时，事实继续未知；不能在解释或最终档案中变成“考试不考代码”等确定结论。区分暂定教学安排和已证实的外部要求。
"""
